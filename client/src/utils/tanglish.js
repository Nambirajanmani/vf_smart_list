// Tamil character to basic phonetic Tanglish transliterator fallback
const TAMIL_VOWELS = {
  'அ': 'a', 'ஆ': 'aa', 'இ': 'i', 'ஈ': 'ee', 'உ': 'u', 'ஊ': 'oo',
  'எ': 'e', 'ஏ': 'ae', 'ஐ': 'ai', 'ஒ': 'o', 'ஓ': 'oa', 'ஔ': 'au'
};

const TAMIL_CONSONANTS = {
  'க': 'k', 'ங': 'ng', 'ச': 's', 'ஞ': 'ny', 'ட': 't', 'ண': 'n',
  'த': 'th', 'ந': 'n', 'ப': 'p', 'ம': 'm', 'ய': 'y', 'ர': 'r',
  'ல': 'l', 'வ': 'v', 'ழ': 'zh', 'ள': 'l', 'ற': 'r', 'ன': 'n',
  'ஜ': 'j', 'ஷ': 'sh', 'ஸ': 's', 'ஹ': 'h'
};

const TAMIL_DIACRITICS = {
  'ா': 'aa', 'ி': 'i', 'ீ': 'ee', 'ு': 'u', 'ூ': 'oo',
  'ெ': 'e', 'ே': 'ae', 'ை': 'ai', 'ொ': 'o', 'ோ': 'oa', 'ௌ': 'au',
  '்': '' // Pulli / virama: cancels implicit 'a'
};

/**
 * Phonetic transliteration from Tamil Unicode text into clean Tanglish.
 */
export function transliterateTamilToTanglish(text) {
  if (!text) return '';
  let result = '';
  const len = text.length;

  for (let i = 0; i < len; i++) {
    const ch = text[i];

    if (TAMIL_VOWELS[ch]) {
      result += TAMIL_VOWELS[ch];
    } else if (TAMIL_CONSONANTS[ch]) {
      const base = TAMIL_CONSONANTS[ch];
      const next = i + 1 < len ? text[i + 1] : null;

      if (next && next === '்') {
        result += base;
        i++; // skip pulli
      } else if (next && TAMIL_DIACRITICS[next] !== undefined) {
        result += base + TAMIL_DIACRITICS[next];
        i++; // skip diacritic
      } else {
        result += base + 'a';
      }
    } else {
      result += ch;
    }
  }

  // Capitalize words
  return result
    .split(' ')
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/**
 * Returns the Tanglish (Tamil in English letters) representation for an item.
 * Always guaranteed to return a valid, clean Tanglish name for any item.
 * e.g.,
 * Tomato         -> "Thakkali"
 * Condensed Milk -> "Kandenst Milk"
 * Condensed Paal -> "Kandenst Milk"
 * Milk           -> "Paal"
 */
export function getTanglishName(item) {
  if (!item) return '';

  // 1. Direct item attribute if explicitly set
  if (item.name_tanglish && item.name_tanglish.trim()) {
    return item.name_tanglish.trim();
  }

  const cleanEn = (item.name || '').toLowerCase().trim();
  const cleanTa = (item.name_ta || '').trim();

  // 2. Direct Tamil script dictionary lookup (exact match)
  if (cleanTa && TAMIL_TO_TANGLISH[cleanTa]) {
    return TAMIL_TO_TANGLISH[cleanTa];
  }

  // 3. Exact dictionary lookup by English or Tanglish name
  if (cleanEn && TANGLISH_DICTIONARY[cleanEn]) {
    return TANGLISH_DICTIONARY[cleanEn];
  }

  // 4. Substring / partial key lookup in English dictionary
  if (cleanEn) {
    for (const [key, val] of Object.entries(TANGLISH_DICTIONARY)) {
      if (cleanEn === key || cleanEn.startsWith(key) || key.startsWith(cleanEn)) {
        return val;
      }
    }
  }

  // 5. Partial Tamil script lookup
  if (cleanTa) {
    for (const [key, val] of Object.entries(TAMIL_TO_TANGLISH)) {
      if (cleanTa.includes(key) || key.includes(cleanTa)) {
        return val;
      }
    }
  }

  // 6. Phonetic transliteration from Tamil script fallback
  if (cleanTa) {
    const transliterated = transliterateTamilToTanglish(cleanTa);
    if (transliterated) return transliterated;
  }

  // 7. Fallback: if name is non-empty, use name
  if (item.name && item.name.trim()) {
    return item.name.trim();
  }

  return '';
}

