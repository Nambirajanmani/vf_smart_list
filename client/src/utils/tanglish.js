/**
 * Returns the proper English word/name for any catalog item.
 * e.g.,
 * Badam          -> "Almond"
 * Thakkali       -> "Tomato"
 * Urulaikizhangu -> "Potato"
 * Vengayam       -> "Onion"
 * Apple          -> "Apple"
 * Condensed Milk -> "Condensed Milk"
 */
export function getEnglishName(item) {
  if (!item) return '';

  // 1. Direct explicit english attribute
  if (item.name_en && item.name_en.trim()) {
    return item.name_en.trim();
  }

  const cleanEn = (item.name || '').toLowerCase().trim();
  const cleanTa = (item.name_ta || '').trim();

  // 2. Direct Tamil script dictionary lookup (exact match)
  if (cleanTa && ENGLISH_DICTIONARY[cleanTa]) {
    return ENGLISH_DICTIONARY[cleanTa];
  }

  // 3. Exact dictionary lookup by name
  if (cleanEn && ENGLISH_DICTIONARY[cleanEn]) {
    return ENGLISH_DICTIONARY[cleanEn];
  }

  // 4. Substring / partial key lookup in English dictionary
  if (cleanEn) {
    for (const [key, val] of Object.entries(ENGLISH_DICTIONARY)) {
      if (cleanEn === key || cleanEn.startsWith(key) || key.startsWith(cleanEn)) {
        return val;
      }
    }
  }

  // 5. Partial Tamil script lookup
  if (cleanTa) {
    for (const [key, val] of Object.entries(ENGLISH_DICTIONARY)) {
      if (cleanTa.includes(key) || key.includes(cleanTa)) {
        return val;
      }
    }
  }

  // 6. Fallback: if name is non-empty, use name
  if (item.name && item.name.trim()) {
    return item.name.trim();
  }

  return '';
}
